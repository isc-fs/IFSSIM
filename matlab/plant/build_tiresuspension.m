%% =======================================================================
function c = pre_code()
L = {
"function [Fz, Vxw, Vyw, AxlTrq, steer_o, susp_travel, in_contact, muScale, camber, WhlPz, WhlVz] = ..."
"         tiresusp_pre(road_valid, road_h, road_mu, road_res, pos, quat, velb, omegab, steer_in, drive_t, brake_t, w_fb)"
"%#codegen"
"% Suspension load and contact-patch kinematics for four corners, plus the"
"% axle torque that drives the tyre block."
"%"
"% Wheel order FL, FR, RL, RR. Body frame ISO 8855: x forward, y LEFT, z up."
""
"Rw = IFSSIM_Rw;"
""
"% Wheel positions in the body frame, at CoG height. y is POSITIVE LEFT, so the"
"% left wheels take +track/2. Getting this backwards mirrors the car and is"
"% almost impossible to see in a lap time."
"rx = [ IFSSIM_aF;  IFSSIM_aF; -IFSSIM_bR; -IFSSIM_bR];"
"ry = [ IFSSIM_tF/2; -IFSSIM_tF/2;  IFSSIM_tR/2; -IFSSIM_tR/2];"
"Fz_static = [IFSSIM_FzF; IFSSIM_FzF; IFSSIM_FzR; IFSSIM_FzR];"
""
"q = quat / max(norm(quat), eps);"
"R = q2r(q);                      % body -> world"
"vel_world   = R * velb;"
"omega_world = R * omegab;"
""
"Fz      = zeros(4,1);  Vxw     = zeros(4,1);  Vyw        = zeros(4,1);"
"AxlTrq  = zeros(4,1);  steer_o = zeros(4,1);  susp_travel= zeros(4,1);"
"camber  = zeros(4,1);"
"% What the VDB suspension block wants, if it is in the model: displacement"
"% from the static ride position in a z-DOWN frame, so positive is droop and"
"% our compression-positive delta is its negative. Measured, see"
"% docs/vdb_step1_port_semantics.md -- feeding it a ride height instead of a"
"% displacement is what made the first attempt return 2568 N a wheel."
"WhlPz   = zeros(4,1);  WhlVz = zeros(4,1);"
"in_contact = zeros(4,1);  muScale = ones(27,4);"
""
"% ---- suspension deflection, all four corners at once ----------------"
"% This has to be a separate pass. An anti-roll bar reacts the DIFFERENCE in"
"% deflection across an axle, so no corner's vertical load can be known until"
"% both corners of its axle are."
"delta  = zeros(4,1);"
"ddelta = zeros(4,1);"
"for i = 1:4"
"    r_w = R * [rx(i); ry(i); 0];"
"    p_w = pos + r_w;                      % corner position, world"
"    % delta > 0 means compressed relative to static ride height."
"    gap       = p_w(3) - (road_h(i) + Rw);    % attachment above wheel centre"
"    delta(i)  = IFSSIM_L0 - gap;"
"    % Compression RATE is the downward velocity of this corner. Using the"
"    % corner velocity rather than the CoG velocity is what makes roll and"
"    % pitch damping appear at all."
"    v_corner  = vel_world + cross(omega_world, r_w);"
"    ddelta(i) = -v_corner(3);"
"end"
""
"% ---- anti-roll bars -------------------------------------------------"
"% A bar carries K_arb times the roll angle of its axle, delivered as a force"
"% couple across the track: dF = K_arb*(dL - dR)/t^2, up on the compressed"
"% side and down on the other, summing to zero so it adds no heave stiffness."
"%"
"% These are not a detail. They are the ONLY thing that makes the front and"
"% rear roll stiffnesses differ, and that difference is the car's balance."
"% With four equal springs and equal tracks -- which is what this model had --"
"% lateral load transfer splits exactly 50.0/50.0 at every steer angle and"
"% nothing can move it, so the car can be neither understeering nor"
"% oversteering by construction. See ifssim_params for how the bar rates come"
"% out of RollStiffnessFront/Rear, which until now were read by nothing."
"arbF = IFSSIM_arbF * (delta(1) - delta(2)) / (IFSSIM_tF*IFSSIM_tF);"
"arbR = IFSSIM_arbR * (delta(3) - delta(4)) / (IFSSIM_tR*IFSSIM_tR);"
"arb  = [arbF; -arbF; arbR; -arbR];"
""
"% ---- camber -----------------------------------------------------------"
"% Inclination each tyre sees: its static setting, plus the share of body roll"
"% the geometry does NOT take back out. Camber gain 1.0 keeps the wheel"
"% upright through the corner; a real double wishbone falls short of that."
"%"
"% Roll comes from the quaternion the chassis already integrates, so this is"
"% the roll the car ACTUALLY has -- not the algebraic estimate the design"
"% model has to make. That is the one place the plant is now ahead of it."
"%"
"% It is wired to the tyre block's Camber input, which this model used to hold"
"% at a constant zero. The tyre does not yet RESPOND to it: the camber"
"% coefficients in the Magic Formula set are zeroed, because nobody has put"
"% this tyre on a rig and inventing PDY3 would be inventing grip. The"
"% kinematics are real and arrive at the tyre; the tyre's answer to them is"
"% the part still waiting on data."
"%"
"% The two terms mirror DIFFERENTLY, and getting that backwards is the easy"
"% mistake. In the ISO tyre axis system y points left on BOTH wheels, so:"
"%"
"%   static camber is symmetric in space -- the tops lean toward each other --"
"%   and therefore reads with OPPOSITE sign on the two sides (sgnOut);"
"%"
"%   roll tilts both wheels the SAME way in space, so it reads with the SAME"
"%   sign on both, and must stay OUTSIDE the mirror."
"%"
"% This used to apply the static setting uniformly to all four and mirror the"
"% roll term -- exactly inverted, on both counts. It changed no force, because"
"% the camber coefficients are zeroed, and it would have changed every one of"
"% them the day rig data arrives. The structure here is not argued from the"
"% convention: it is what the VDB double-wishbone block measurably does"
"% (see vdb_camber_mask), and the two now agree to 3e-10 deg."
"%"
"% The OVERALL SIGN of gamma is still unpinned. Nothing in this plant can"
"% settle it while the Magic Formula camber terms are zero -- there is no"
"% observable to check it against. It wants fixing against rig data, not"
"% against an argument."
"rollAng = atan2(2*(q(1)*q(2) + q(3)*q(4)), 1 - 2*(q(2)*q(2) + q(3)*q(3)));"
"sgnOut  = [-1; 1; -1; 1];"
"camber  = sgnOut .* [IFSSIM_camF; IFSSIM_camF; IFSSIM_camR; IFSSIM_camR] + ..."
"          (1 - [IFSSIM_cgainF; IFSSIM_cgainF; IFSSIM_cgainR; IFSSIM_cgainR]) * rollAng;"
""
"for i = 1:4"
"    r_b = [rx(i); ry(i); 0];"
"    r_w = R * r_b;"
"    p_w = pos + r_w;                      % corner position, world"
""
"    kw_i = IFSSIM_kwF; if i > 2, kw_i = IFSSIM_kwR; end"
"    Fz_i = Fz_static(i) + kw_i * delta(i) + IFSSIM_cw * ddelta(i) + arb(i);"
""
"    % A tyre cannot pull the road. Clamping here is what lets a wheel lift"
"    % in a corner instead of generating negative grip."
"    if Fz_i < 0, Fz_i = 0; end"
"    % Contact needs the platform to have actually CHARACTERISED the ground,"
"    % not merely to have hit something with one ray."
"    %"
"    % A NEGATIVE residual is the platform saying it could not fit a plane at"
"    % all - fewer than three of its rays hit - so it does not know what is"
"    % under this wheel. Standing on an answer nobody has is how a wheel ends"
"    % up loaded against geometry that is not there."
"    %"
"    % A LARGE residual is a different thing entirely and deliberately does NOT"
"    % remove contact. It means the patch spans a step or a kerb edge: the"
"    % ground is poorly described by a plane, but the tyre is still touching"
"    % it. Dropping Fz there would make the car fall through every kerb, which"
"    % is worse than the flat-plane approximation it would be replacing."
"    fit_known = (road_res(i) >= 0);"
"    contact = (road_valid(i) > 0.5) && (Fz_i > 0) && fit_known;"
"    if ~contact, Fz_i = 0; end"
""
"    % ---- contact-patch velocity ------------------------------------"
"    v_b = velb + cross(omegab, r_b);"
"    d   = steer_in(i);"
"    cd  = cos(d); sd = sin(d);"
"    vx =  v_b(1)*cd + v_b(2)*sd;          % along the wheel"
"    vy = -v_b(1)*sd + v_b(2)*cd;          % across it"
""
"    % ---- axle torque -----------------------------------------------"
"    % The tyre block's own brake and rolling-resistance models are switched"
"    % off, so both arrive here as torque on the axle instead."
"    %"
"    % w_fb is last step's wheel speed, delayed. Using it rather than the"
"    % block's live Omega is what keeps this out of an algebraic loop; at"
"    % 1/960 s the wheel cannot turn far enough in one step for the"
"    % difference to matter."
"    %"
"    % tanh, not sign: sign() chatters about zero every step at 1/960 s. tanh"
"    % also means both torques fade smoothly to zero as the wheel stops, so"
"    % they RESIST motion but cannot HOLD a stopped car - arresting creep"
"    % entirely needs a stiction term, which this is not."
"    % Smoothed over IFSSIM_wreg, which is deliberately WIDER than the wheel"
"    % speed one step of brake torque can produce. Narrower than that and this"
"    % is sign() in all but name, and the stop ends in a limit cycle."
"    dirw    = tanh(w_fb(i) / IFSSIM_wreg);"
"    % LOCK, DO NOT REVERSE. Brake torque is a magnitude opposing rotation, so"
"    % it must never be large enough to drive the wheel backwards through zero."
"    % The old hand-written tyre clamped the wheel state directly after"
"    % integrating; wheel spin now lives inside the tyre block, where we cannot"
"    % reach it, so the limit has to be applied to the TORQUE instead."
"    %"
"    % Iw*|w|/Ts is exactly the torque that brings this wheel to rest in one"
"    % step. Anything beyond it would reverse the wheel, which a brake cannot"
"    % do: at 286 N.m on Iw = 0.21 one step moves the wheel 1.4 rad/s, so"
"    % without this the EBS walks a stopping wheel backwards through zero."
"    T_cap   = IFSSIM_Iw * abs(w_fb(i)) / IFSSIM_Ts;"
"    T_brake = min(brake_t(i), T_cap) * dirw;"
"    % Rolling resistance. Physically the contact patch's pressure"
"    % distribution shifts forward of the axle and the resulting moment"
"    % opposes rotation. Modelling it as a drag force on the chassis would"
"    % give a similar top speed and the wrong wheel dynamics."
"    T_roll  = IFSSIM_Crr * Fz_i * Rw * dirw;"
"    AxlTrq(i) = drive_t(i) - T_brake - T_roll;"
""
"    % ---- friction scaling ------------------------------------------"
"    % The tyre carries one set of coefficients, but the road can differ under"
"    % each wheel. Magic Formula takes a column of 27 SCALING FACTORS per"
"    % wheel, and two of them scale peak friction; everything else stays 1."
"    %"
"    % Indices 3 and 10 are LMUX and LMUY in the standard Magic Formula"
"    % ordering. That ordering is not documented on the block and the code"
"    % behind it is P-coded, so it was checked instead of assumed: perturbing"
"    % each of the 27 in turn, 19 and 20 moved the combined-slip coupling,"
"    % which is exactly where the standard order puts LXAL and LYKA, and 3"
"    % scaled lateral grip directly in a pure-slip test. Both mu factors are"
"    % set to the same ratio, so a road reporting the nominal mu scales by 1."
"    muw = road_mu(i);"
"    if muw <= 0, muw = IFSSIM_mu; end"
"    mur = muw / IFSSIM_mu;"
"    muScale(3,i)  = mur;"
"    muScale(10,i) = mur;"
""
"    Fz(i)=Fz_i; Vxw(i)=vx; Vyw(i)=vy; steer_o(i)=d;"
"    susp_travel(i)=delta(i); in_contact(i)=double(contact);"
"    WhlPz(i) = -delta(i);  WhlVz(i) = -ddelta(i);"
"end"
"end"
""
"function R = q2r(q)"
"%#codegen"
"w=q(1); x=q(2); y=q(3); z=q(4);"
"R = [1-2*(y*y+z*z),   2*(x*y-z*w),   2*(x*z+y*w); ..."
"       2*(x*y+z*w), 1-2*(x*x+z*z),   2*(y*z-x*w); ..."
"       2*(x*z-y*w),   2*(y*z+x*w), 1-2*(x*x+y*y)];"
"end"
};
c = char(strjoin(string(L), newline));
end

%% =======================================================================
function c = post_code()
L = {
"function [omega, fz, fx, fy, slip_ratio, slip_angle, tyre_force, tyre_torque] = ..."
"         tiresusp_post(Fx_in, Fy_in, Fz_in, Om, steer_in, Vxw, Vyw)"
"%#codegen"
"% Four wheel forces, in their own wheel frames, assembled into one body-frame"
"% wrench -- plus the reported per-wheel state."
""
"rx = [ IFSSIM_aF;  IFSSIM_aF; -IFSSIM_bR; -IFSSIM_bR];"
"ry = [ IFSSIM_tF/2; -IFSSIM_tF/2;  IFSSIM_tR/2; -IFSSIM_tR/2];"
"Rw = IFSSIM_Rw;"
""
"omega = reshape(Om,    4, 1);"
"fx    = reshape(Fx_in, 4, 1);"
"fy    = reshape(Fy_in, 4, 1);"
"fz    = reshape(Fz_in, 4, 1);"
""
"slip_ratio = zeros(4,1);  slip_angle = zeros(4,1);"
"F_sum = zeros(3,1);       M_sum      = zeros(3,1);"
""
"for i = 1:4"
"    % Slip is REPORTED here, not used. The tyre block computes its own"
"    % internally, with relaxation; this is the algebraic value, recomputed"
"    % for telemetry so the bus still carries the quantity it always did."
"    vref = max(abs(Vxw(i)), IFSSIM_vreg);"
"    slip_ratio(i) = (omega(i)*Rw - Vxw(i)) / vref;"
"    slip_angle(i) = atan2(Vyw(i), vref);"
""
"    % Wheel frame -> body frame. Fx acts along the wheel, Fy across it, and"
"    % the wheel is rotated by the steer angle relative to the body."
"    d  = steer_in(i);"
"    cd = cos(d); sd = sin(d);"
"    Fb = [fx(i)*cd - fy(i)*sd; fx(i)*sd + fy(i)*cd; fz(i)];"
"    F_sum = F_sum + Fb;"
""
"    % The tyre force acts at the CONTACT PATCH, on the road, not at the CoG."
"    % That arm IS load transfer: it is what turns a lateral force into a roll"
"    % moment and a longitudinal force into a pitch moment."
"    %"
"    % This used to be [rx; ry; 0], and the reason it survived so long is that"
"    % a zero z still gives the RIGHT answer for three of the six terms. Yaw"
"    % (rx*fy - ry*fx) has no z in it at all, and the roll and pitch from the"
"    % VERTICAL loads (ry*fz, -rx*fz) do not either. So the car rolled"
"    % correctly whenever something else rolled it -- which is every test that"
"    % imposes a body rate. What it could not do was roll ITSELF: the two"
"    % missing terms, -rz*fy and +rz*fx, are precisely the ones by which the"
"    % tyres act on the body. Measured before the fix: 0.000000 rad of roll in"
"    % a 1.2 g corner, and load transfer at 0.1% of what m*a*h/t requires."
"    %"
"    % Taking the arm all the way to the ground puts the roll centre at ground"
"    % level, so every newton of lateral transfer goes through the springs and"
"    % none through the suspension links. That is a real assumption and it is"
"    % stated here rather than hidden: this model HAS no links -- no wishbones,"
"    % no instantaneous centres -- so a non-zero roll centre would not be a"
"    % better number, it would be an invented one. It costs less than it"
"    % sounds: the TOTAL transfer is m*a*h/t whatever the roll centre does."
"    % What a real one would change is the elastic/geometric split, and with"
"    % it the roll ANGLE and the transient, not the steady-state load split."
"    %"
"    % The height is held constant at the static CoG height. Tracking ride"
"    % height through suspension travel would be a centimetre of correction on"
"    % a 34 cm arm, sitting on top of a CoG height nobody has measured."
"    M_sum = M_sum + cross([rx(i); ry(i); -IFSSIM_CoGH], Fb);"
"end"
""
"tyre_force  = F_sum;"
"tyre_torque = M_sum;"
"end"
};
c = char(strjoin(string(L), newline));
end

% -------------------------------------------------------------------------
function tag_camber_probe(name, TY)
%TAG_CAMBER_PROBE  Log whatever reaches the tyre's Camber input.
%
%   The camber coefficients in the Magic Formula set are zeroed (no rig
%   data), so camber changes NO force -- which means no wrench comparison
%   can tell a correct camber path from a severed one. vdb_step2_check
%   found exactly that: it passed a mutant. The signal itself is therefore
%   the only honest observable, so it is named and logged here.
lh = get_param([name '/' TY],'LineHandles');
set_param(lh.Inport(4),'Name','camber_at_tyre');
% Logging lives on the SOURCE PORT, not on the line -- lines carry only the
% name. Setting it on the line fails with "no parameter named DataLogging".
set_param(get_param(lh.Inport(4),'SrcPortHandle'), ...
          'DataLogging','on','DataLoggingNameMode','SignalName');
set_param(name,'SignalLogging','on','SignalLoggingName','tsLog');
end

% -------------------------------------------------------------------------
function tag_probe(name, blk, port, signame)
%TAG_PROBE  Name and log one output port, so a check can read it by name.
%
%   Same reason as tag_camber_probe: the quantity being verified has to be
%   observable. Logging both the block's force and ours in the SAME run beats
%   comparing across two builds -- there is no second build to drift.
ph = get_param([name '/' blk],'PortHandles');
set_param(ph.Outport(port),'DataLogging','on', ...
          'DataLoggingNameMode','Custom','DataLoggingName',signame);
set_param(name,'SignalLogging','on','SignalLoggingName','tsLog');
end
