"""Simulator-in-the-loop run dirs -> RunBundle, plus per-group aggregation.

Reads the layout written by ``mock_sim.write_run`` (and, later, by the real
SIL runner). One seed = one ``sim_e2e`` bundle. N seeds of one
(scenario, commit[, params]) = one ``sim_aggregate`` / ``sim_sweep_trial``
bundle. Trackers can't aggregate summary scalars across a group, so this is
where finish rate, lap-time CI and the rest are computed.
"""

from __future__ import annotations

import csv
import json
import math
import warnings
from datetime import datetime
from pathlib import Path
from typing import Any, Iterable

import numpy as np

from .. import provenance
from ..bundle import SCHEMA_VERSION, Event, RunBundle, Series, Table


def _read_csv(path: Path) -> dict[str, np.ndarray | list[str]]:
    with path.open(newline="") as fh:
        rows = list(csv.DictReader(fh))
    if not rows:
        return {}
    out: dict[str, Any] = {}
    for k in rows[0]:
        vals = [r[k] for r in rows]
        try:
            out[k] = np.array(
                [float(v) if v not in ("", "None") else math.nan for v in vals]
            )
        except ValueError:
            out[k] = vals
    return out


def _rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="") as fh:
        return [
            r
            for r in csv.DictReader(fh)
            if any(v not in ("", "None") for v in r.values())
        ]


def _num(v: str | None) -> float | None:
    try:
        return float(v) if v not in (None, "", "None") else None
    except ValueError:
        return None


def scenario_fields(man: dict[str, Any]) -> dict[str, Any]:
    sc = man["scenario"]
    return {
        "kind": "sim",
        "name": sc["name"],
        "event": sc["event"],
        "laps": sc["laps"],
        "track": sc["track"]["name"],
        "noise": sc["noise"],
        "sim_build": man["code"]["sim_build"]["id"],
    }


def load_sim_run(run_dir: Path, tracks_dir: Path | None = None) -> RunBundle:
    man = json.loads((run_dir / "manifest.json").read_text())
    res = json.loads((run_dir / "results.json").read_text())
    sfields = scenario_fields(man)
    sid = provenance.scenario_id(sfields)
    pipe = man["code"]["pipeline"]
    params = man.get("params", {})
    sweep = man.get("sweep")
    group = f"{sid}@{pipe['sha']}" + (f"/trial{sweep['trial']:02d}" if sweep else "")
    tags = list(man.get("tags", [])) + [
        f"scenario:{sfields['name']}",
        f"event:{sfields['event']}",
    ]
    finished = bool(res.get("race/finished"))
    started = datetime.fromisoformat(man["started_at"])
    b = RunBundle(
        job_type=man.get("job_type", "sim_e2e"),
        name=f"sim/{sfields['name']}/{pipe['sha']}/seed{man['seed']}"
        + (f"/t{sweep['trial']:02d}" if sweep else ""),
        group=group,
        source_dir=run_dir,
        started_at=started,
        status="finished" if finished else "failed",
        tags=tags + ([] if finished else ["dnf"]),
        notes="MOCK simulator run (generated by bench_tracking.mock_sim) — numbers are synthetic.",
    )
    b.config = {
        "schema_version": SCHEMA_VERSION,
        "job_type": b.job_type,
        "mock": bool(man.get("mock")),
        "code": man["code"],
        "scenario": {
            "id": sid,
            **sfields,
            "seed": man["seed"],
            "track_length_m": man["scenario"]["track"]["length_m"],
            "track_csv": man["scenario"]["track"]["csv"],
        },
        "params": params,
        "referee": man["referee"],
        "sweep": sweep,
        "nightly": man.get("nightly"),
        "env": {"started_at": man["started_at"]},
        "provenance": {"complete": True, "missing": []},
    }
    b.summary.update({k: v for k, v in res.items()})

    tel = _read_csv(run_dir / "telemetry.csv")
    # distance-indexed series (the primary x axis for sim runs)
    b.add_series(
        Series(
            "sim_track",
            "track/s_m",
            tel["s_m"],
            {
                k: tel[k]
                for k in (
                    "cte_m",
                    "heading_err_rad",
                    "speed_mps",
                    "lat_acc_mps2",
                    "steering_rad",
                    "throttle",
                    "brake",
                    "slam_err_m",
                    "odom_err_m",
                    "lap",
                    "s_lap_m",
                    "t_s",
                )
            },
        )
    )
    b.add_series(
        Series(
            "sim_time",
            "t/sim_s",
            tel["t_s"],
            {
                k: tel[k]
                for k in (
                    "speed_mps",
                    "steering_rad",
                    "throttle",
                    "brake",
                    "cte_m",
                    "s_m",
                )
            },
        )
    )
    per = _read_csv(run_dir / "perception.csv")
    b.add_series(
        Series(
            "sim_perception",
            "t/sim_s",
            per["t_s"],
            {
                "n_gt": per["n_gt"],
                "n_tp": per["n_tp"],
                "n_fp": per["n_fp"],
                "n_fn": per["n_fn"],
                "recall": per["recall"],
                "precision": per["precision"],
                "pos_err_mean_m": per["pos_err_mean_m"],
                "s_m": per["s_m"],
            },
        )
    )
    lat = _read_csv(run_dir / "latency.csv")
    b.add_series(
        Series(
            "sim_latency", "t/sim_s", lat["t_s"], {k: lat[k] for k in lat if k != "t_s"}
        )
    )

    laps = _rows(run_dir / "laps.csv")
    lap_rows = [
        [
            int(float(r["lap"])),
            _num(r["time_s"]),
            int(float(r["doo"])),
            int(float(r["off_course"])),
            int(float(r["completed"])),
        ]
        for r in laps
    ]
    b.add_table(
        Table(
            "laps",
            ["lap", "time_s", "doo", "off_course", "completed"],
            lap_rows,
            "Referee lap table",
        )
    )
    # per-lap series (x = lap) so lap-time plots overlay across seeds/commits
    done = [r for r in lap_rows if r[4]]
    if done:
        b.add_series(
            Series(
                "sim_laps",
                "lap",
                [r[0] for r in done],
                {
                    "lap_time_s": [r[1] for r in done],
                    "doo": [r[2] for r in done],
                    "off_course": [r[3] for r in done],
                },
            )
        )

    # per-lap control quality
    lap_ids = np.unique(tel["lap"])
    b.add_table(
        Table(
            "lap_quality",
            ["lap", "cte_rms_m", "cte_max_m", "speed_mean_mps", "slam_err_rms_m"],
            [
                [
                    int(lp),
                    float(np.sqrt(np.mean(tel["cte_m"][tel["lap"] == lp] ** 2))),
                    float(np.abs(tel["cte_m"][tel["lap"] == lp]).max()),
                    float(tel["speed_mps"][tel["lap"] == lp].mean()),
                    float(np.sqrt(np.mean(tel["slam_err_m"][tel["lap"] == lp] ** 2))),
                ]
                for lp in lap_ids
            ],
            "Per-lap control / localisation quality",
        )
    )

    # trajectory (GT, SLAM) in the sim world frame
    rows = [
        [float(t), "gt", float(x), float(y), float(s), int(lp)]
        for t, x, y, s, lp in zip(
            tel["t_s"], tel["x"], tel["y"], tel["s_lap_m"], tel["lap"]
        )
    ]
    rows += [
        [float(t), "slam", float(x), float(y), float(s), int(lp)]
        for t, x, y, s, lp in zip(
            tel["t_s"], tel["slam_x"], tel["slam_y"], tel["s_lap_m"], tel["lap"]
        )
    ]
    b.add_table(
        Table(
            "trajectory",
            ["t_s", "source", "x", "y", "s_lap_m", "lap"],
            rows,
            "GT and SLAM positions, sim world frame (all runs of a track share it)",
        )
    )
    m = _rows(run_dir / "map_cones.csv")
    b.add_table(
        Table(
            "map_cones",
            ["x", "y", "source", "color"],
            [[float(r["x"]), float(r["y"]), r["source"], r["color"]] for r in m],
            "GT track + SLAM map",
        )
    )
    pr = _rows(run_dir / "perception_range.csv")
    b.add_table(
        Table(
            "perception_range",
            ["range_lo_m", "range_hi_m", "n_gt", "n_tp", "recall", "pos_err_mean_m"],
            [
                [
                    _num(r["range_lo_m"]),
                    _num(r["range_hi_m"]),
                    int(float(r["n_gt"])),
                    int(float(r["n_tp"])),
                    _num(r["recall"]),
                    _num(r["pos_err_mean_m"]),
                ]
                for r in pr
            ],
            "Recall and position error per GT range bin",
        )
    )
    for r in _rows(run_dir / "events.csv"):
        b.events.append(
            Event(
                _num(r.get("t_s")),
                "referee" if r["kind"] in ("doo", "off_course", "dnf") else "pipeline",
                r["kind"],
                r["severity"],
                r["detail"],
                s_m=_num(r.get("s_m")),
                x=_num(r.get("x")),
                y=_num(r.get("y")),
            )
        )
    for p in sorted(run_dir.glob("*.csv")):
        b.files.append((p, "data"))
    b.files += [
        (run_dir / "manifest.json", "provenance"),
        (run_dir / "results.json", "data"),
    ]
    return b


def _ci95(x: list[float]) -> float | None:
    x = [v for v in x if v is not None and math.isfinite(v)]
    if len(x) < 2:
        return None
    return 1.96 * float(np.std(x, ddof=1)) / math.sqrt(len(x))


def aggregate(seeds: list[RunBundle], *, job_type: str = "sim_aggregate") -> RunBundle:
    """N seed bundles of one group -> one aggregate bundle."""
    first = seeds[0]
    cfg = json.loads(json.dumps(first.config, default=str))
    cfg["scenario"].pop("seed", None)
    cfg["job_type"] = job_type
    cfg["seeds"] = [s.config["scenario"]["seed"] for s in seeds]
    b = RunBundle(
        job_type=job_type,
        name=(
            f"agg/{cfg['scenario']['name']}/{cfg['code']['pipeline']['sha']}"
            + (f"/t{cfg['sweep']['trial']:02d}" if cfg.get("sweep") else "")
        ),
        group=first.group,
        source_dir=first.source_dir.parent if first.source_dir else None,
        started_at=max(s.started_at for s in seeds),
        status="finished",
        tags=sorted(
            {t for s in seeds for t in s.tags if t not in ("dnf",)} | {"aggregate"}
        ),
        config=cfg,
        notes=f"Aggregate of {len(seeds)} seeds. " + first.notes,
    )
    keys = sorted(
        {k for s in seeds for k, v in s.summary.items() if isinstance(v, (int, float))}
    )
    S = b.summary
    for k in keys:
        vals = [s.summary.get(k) for s in seeds]
        vals = [float(v) for v in vals if v is not None and math.isfinite(float(v))]
        if vals:
            S[k] = float(np.mean(vals))
            S[f"{k}.std"] = float(np.std(vals, ddof=1)) if len(vals) > 1 else 0.0
            S[f"{k}.min"] = min(vals)
            S[f"{k}.max"] = max(vals)
    fin = [int(bool(s.summary.get("race/finished"))) for s in seeds]
    S["race/finish_rate_frac"] = float(np.mean(fin))
    S["race/n_dnf"] = int(len(fin) - sum(fin))
    lap_means = [s.summary.get("race/lap_time_mean_s") for s in seeds]
    S["race/lap_time_mean_ci95_s"] = _ci95(lap_means)
    S["run/n_seeds"] = len(seeds)

    # per-seed table
    cols = [
        "seed",
        "finished",
        "n_laps",
        "lap_time_mean_s",
        "lap_time_best_s",
        "n_doo",
        "n_off_track",
        "cross_track_rms_m",
        "recall",
        "slam_err_rms_m",
        "e2e_p95_ms",
        "first_failure_s_m",
        "run",
    ]
    b.add_table(
        Table(
            "seeds",
            cols,
            [
                [
                    s.config["scenario"]["seed"],
                    s.summary.get("race/finished"),
                    s.summary.get("race/n_laps"),
                    s.summary.get("race/lap_time_mean_s"),
                    s.summary.get("race/lap_time_best_s"),
                    s.summary.get("race/n_doo"),
                    s.summary.get("race/n_off_track"),
                    s.summary.get("control/cross_track_rms_m"),
                    s.summary.get("perception/recall_frac"),
                    s.summary.get("slam/pos_err_rms_m"),
                    s.summary.get("latency/e2e_p95_ms"),
                    s.summary.get("race/first_failure_s_m"),
                    s.name,
                ]
                for s in seeds
            ],
            "One row per seed",
        )
    )
    # all laps of all seeds
    b.add_table(
        Table(
            "laps",
            ["seed", "lap", "time_s", "doo", "off_course", "completed"],
            [
                [s.config["scenario"]["seed"], *r]
                for s in seeds
                for r in s.tables["laps"].rows
            ],
            "Every lap of every seed",
        )
    )
    # failure / penalty events of all seeds
    b.events = [
        Event(
            e.t_s,
            e.node,
            e.kind,
            e.severity,
            f"seed {s.config['scenario']['seed']}: {e.detail}",
            e.s_m,
            e.x,
            e.y,
        )
        for s in seeds
        for e in s.events
        if e.kind in ("doo", "off_course", "dnf", "lateral_disturbance")
    ]
    # mean-over-seeds distance profile (binned on lap distance, racing laps only)
    L = float(first.config["scenario"]["track_length_m"])
    edges = np.arange(0, L + 2, 2.0)
    prof: dict[str, list[np.ndarray]] = {
        k: [] for k in ("cte_m", "speed_mps", "slam_err_m")
    }
    for s in seeds:
        ts = s.series["sim_track"]
        racing = ts.values["lap"] > (1 if first.config["scenario"]["laps"] > 1 else 0)
        idx = np.digitize(ts.values["s_lap_m"][racing], edges) - 1
        for k in prof:
            v = ts.values[k][racing]
            if k == "cte_m":
                v = np.abs(v)
            sums = np.bincount(idx, v, len(edges))[: len(edges) - 1]
            cnt = np.bincount(idx, None, len(edges))[: len(edges) - 1]
            prof[k].append(np.where(cnt > 0, sums / np.maximum(cnt, 1), np.nan))
    centers = (edges[:-1] + edges[1:]) / 2
    vals = {}
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", RuntimeWarning)  # bins no seed reached
        for k, arrs in prof.items():
            a = np.vstack(arrs)
            vals[f"{k}_mean"] = np.nanmean(a, 0)
            vals[f"{k}_max"] = np.nanmax(a, 0)
    b.add_series(Series("agg_track_profile", "track/s_lap_m", centers, vals))
    b.add_table(first.tables["map_cones"])
    return b


def group_runs(bundles: Iterable[RunBundle]) -> dict[str, list[RunBundle]]:
    out: dict[str, list[RunBundle]] = {}
    for b in bundles:
        out.setdefault(b.group, []).append(b)
    for v in out.values():
        v.sort(key=lambda b: b.config["scenario"]["seed"])
    return out
